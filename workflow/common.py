def ensure_dirs(cfg: dict[str, Any]) -> None:
    for p in [
        workdir(cfg), results_dir(cfg), logdir(cfg),
        workdir(cfg) / "runs", workdir(cfg) / "references",
        results_dir(cfg) / "tables", results_dir(cfg) / "figures", results_dir(cfg) / "provenance",
        Path(cfg.get("resources", {}).get("lock_root", "work/.resource_locks")),
    ]:
        p.mkdir(parents=True, exist_ok=True)


def workflow_env(extra: dict[str, str] | None = None) -> dict[str, str]:
    """Prevent implicit BLAS/OpenMP oversubscription inside many workers."""
    env = os.environ.copy()
    env.update({
        "OMP_NUM_THREADS": "1",
        "OPENBLAS_NUM_THREADS": "1",
        "MKL_NUM_THREADS": "1",
        "NUMEXPR_NUM_THREADS": "1",
        "VECLIB_MAXIMUM_THREADS": "1",
        "MALLOC_ARENA_MAX": "4",
        "LC_ALL": env.get("LC_ALL", "C"),
    })
    if extra:
        env.update({str(k): str(v) for k, v in extra.items()})
    return env


def run_cmd(cmd: list[str] | str, *, log: Path | None = None, shell: bool = False,
            check: bool = True, env: dict[str, str] | None = None) -> subprocess.CompletedProcess:
    effective_env = workflow_env(env)
    if log:
        log.parent.mkdir(parents=True, exist_ok=True)
        with log.open("a", encoding="utf-8") as fh:
            fh.write("\n[CMD] " + (cmd if isinstance(cmd, str) else " ".join(map(str, cmd))) + "\n")
            fh.flush()
            return subprocess.run(cmd, shell=shell, check=check, stdout=fh,
                                  stderr=subprocess.STDOUT, text=True, env=effective_env)
    return subprocess.run(cmd, shell=shell, check=check, text=True, env=effective_env)


def run_cmd_retry(cmd: list[str] | str, *, attempts: int = 4, sleep_seconds: int = 20,
                  log: Path | None = None, shell: bool = False,
                  env: dict[str, str] | None = None) -> subprocess.CompletedProcess:
    last: Exception | None = None
    for attempt in range(1, attempts + 1):
        try:
            return run_cmd(cmd, log=log, shell=shell, check=True, env=env)
        except Exception as exc:
            last = exc
            if log:
                with log.open("a", encoding="utf-8") as fh:
                    fh.write(f"[WARN] command attempt {attempt}/{attempts} failed: {exc}\n")
            if attempt < attempts:
                time.sleep(sleep_seconds * attempt)
    assert last is not None
    raise last


def command_exists(name: str) -> bool:
    return shutil.which(name) is not None


def sha256(path: str | Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for block in iter(lambda: fh.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def open_text(path: str | Path, mode: str = "rt"):
    path = Path(path)
    return gzip.open(path, mode) if path.suffix == ".gz" else open(path, mode, encoding=None if "b" in mode else "utf-8")


def iter_fasta(path: str | Path):
    header: str | None = None
    seq: list[str] = []
    with open_text(path, "rt") as fh:
        for line in fh:
            line = line.rstrip("\n")
            if line.startswith(">"):
                if header is not None:
                    yield header, "".join(seq)
                header = line[1:]
                seq = []
            else:
                seq.append(line.strip())
        if header is not None:
            yield header, "".join(seq)


def write_fasta_record(fh, header: str, seq: str, width: int = 80) -> None:
    fh.write(">" + header + "\n")
    for i in range(0, len(seq), width):
        fh.write(seq[i : i + width] + "\n")


def read_qname_set(path: str | Path) -> set[str]:
    p = Path(path)
    if not p.exists() or p.stat().st_size == 0:
        return set()
    with open_text(p, "rt") as fh:
        return {line.strip() for line in fh if line.strip()}


def write_tsv(path: str | Path, rows: Iterable[dict[str, Any]], fieldnames: list[str] | None = None) -> None:
    rows = list(rows)
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    if fieldnames is None:
        fieldnames = list(rows[0].keys()) if rows else []
    with p.open("w", newline="", encoding="utf-8") as fh:
        if not fieldnames:
            return
        w = csv.DictWriter(fh, fieldnames=fieldnames, delimiter="\t", extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)


def atomic_json(path: str | Path, obj: Any) -> None:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_suffix(p.suffix + ".tmp")
    tmp.write_text(json.dumps(obj, indent=2, ensure_ascii=False), encoding="utf-8")
    tmp.replace(p)


def normalize_qname(name: str) -> str:
    token = name.strip().split()[0]
    if token.endswith("/1") or token.endswith("/2"):
        token = token[:-2]
    return token


def fail(msg: str, code: int = 1) -> None:
    print(f"[ERROR] {msg}", file=sys.stderr)
    raise SystemExit(code)




