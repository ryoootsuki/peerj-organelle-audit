def deep_merge(a: dict[str, Any], b: dict[str, Any]) -> dict[str, Any]:
    out = dict(a)
    for k, v in b.items():
        if k in out and isinstance(out[k], dict) and isinstance(v, dict):
            out[k] = deep_merge(out[k], v)
        else:
            out[k] = v
    return out


def _read_yaml(path: str | Path) -> dict[str, Any]:
    with open(path, encoding="utf-8") as fh:
        return yaml.safe_load(fh) or {}


def load_config(species_config: str | Path, common_config: str | Path = "config/common.yaml") -> dict[str, Any]:
    """Load common, hardware profile, species, and optional runtime override.

    Merge order is deliberate: common < hardware profile < species < runtime.
    The runtime file affects performance only and is generated by autotuning.
    """
    common = _read_yaml(common_config)
    cfg = dict(common)
    profile_path = common.get("workflow", {}).get("resource_profile")
    if profile_path and Path(profile_path).exists():
        cfg = deep_merge(cfg, _read_yaml(profile_path))
    species = _read_yaml(species_config)
    cfg = deep_merge(cfg, species)
    runtime_path = os.environ.get(
        "WORKFLOW_RUNTIME_CONFIG",
        str(common.get("workflow", {}).get("runtime_config", "config/runtime.auto.yaml")),
    )
    if runtime_path and Path(runtime_path).exists():
        cfg = deep_merge(cfg, _read_yaml(runtime_path))
    cfg["_species_config"] = str(species_config)
    cfg["_common_config"] = str(common_config)
    cfg["_resource_profile"] = str(profile_path or "")
    cfg["_runtime_config"] = str(runtime_path or "")
    return cfg


def species_id(cfg: dict[str, Any]) -> str:
    return str(cfg["species"]["id"])


